#!/bin/bash
# Evaluate the submitted checkpoint on RoboTwin 2.0: 50 tasks x {demo_clean, demo_randomized} x 100 episodes.
#
# Inference setting used for the reported results:
#   - FP32 inference server (official release-validation setting; BF16 changes success rates)
#   - robot config robotwin_clean (clean-only normalization stats, same as training)
#   - USE_LENGTH (default 50 = official): number of the 50 predicted actions executed per inference call before
#     re-planning. 25 gave +3.8 pp on the 16 hardest tasks in our ablation (see reproduction_report.md); the value used
#     for the submitted results.json is stated in the report.
#
# scripts/start_eval.sh is the official experiment/robotwin/start_robotwin_infer_and_eval.sh plus:
#   SIMS_PER_SERVER=k  k simulators share one FP32 policy server (stateless full forward per request)
#   EVAL_TASKS="..."   task subset/order;  GPU_OFFSET  first GPU;  EVAL_RUN_DIR  resumable run directory
# The RoboTwin client (generated by scripts/make_timed_client.py, also in src/patches/RoboTwin.patch) records every
# episode to lb_resume.jsonl so an interrupted evaluation resumes where it stopped.
#
# Usage: ROBOTWIN_DIR=/path/to/RoboTwin LINGBOT_DIR=/path/to/lingbot-vla-v2 CKPT=../03_模型权重/checkpoint OUT=./eval_out bash eval.sh
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROBOTWIN_DIR=${ROBOTWIN_DIR:?set ROBOTWIN_DIR (RoboTwin 2.0 at the pinned commit, src/patches/RoboTwin.patch applied)}
LINGBOT_DIR=${LINGBOT_DIR:?set LINGBOT_DIR (lingbot-vla-v2 with src/patches/lingbot-vla-v2.patch applied)}
CKPT=${CKPT:-$HERE/../03_模型权重/main_aug/checkpoints/global_step_51456/hf_ckpt}
OUT=${OUT:-$PWD/eval_out}
CONDA_SH=${CONDA_SH:-$HOME/miniconda3/etc/profile.d/conda.sh}
INFER_ENV=${INFER_ENV:-lingbot}; SIM_ENV=${SIM_ENV:-RoboTwin}
SIMS=${SIMS_PER_SERVER:-8}                          # 1 FP32 server (~27 GB) + 8 sims (~6 GB each) fit a 96 GB GPU
USE_LENGTH=${USE_LENGTH:-25}
TEAM_ID=${TEAM_ID:-replace_with_your_team_id}

cd $LINGBOT_DIR
one(){ # setting first_gpu port
  EVAL_RUN_DIR=$OUT/$1/run LB_TEST_NUM=100 EVAL_MAX_RETRIES=20 SIMS_PER_SERVER=$SIMS GPU_OFFSET=$2 \
  bash $HERE/scripts/start_eval.sh \
    --model_path $CKPT --inference_workdir $LINGBOT_DIR/ --eval_workdir $ROBOTWIN_DIR \
    --output_base $OUT/$1 --conda_sh $CONDA_SH --inference_env $INFER_ENV --sim_env $SIM_ENV \
    --robo_name robotwin_clean --task_config demo_$1 --num_tasks 50 --num_gpus 2 --num_per_gpu 1 \
    --start_port $3 --use_length $USE_LENGTH --use_fp32 True --use_bf16 False
}
one clean 0 9700 &            # GPUs 0-1
sleep 5
one randomized 2 9750 &       # GPUs 2-3
wait

# official results.json (first 100 valid seeds per task in seed order; simulator crashes count as failures)
python3 $HERE/scripts/make_results_json.py $OUT $TEAM_ID $OUT/results.json
